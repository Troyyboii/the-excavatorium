import { defineConfig } from "@lovable.dev/vite-tanstack-config";
import { mcpPlugin } from "@lovable.dev/mcp-js/stacks/tanstack/vite";

// @lovable.dev/mcp-js 0.26.1 compares Vite's slash-normalized root with a
// Windows path.resolve result and aborts before the app can build. The MCP
// routes are tracked/generated source files, so retain them on Windows while
// keeping the plugin active everywhere else.
const mcpVitePlugins = process.platform === "win32" ? [] : [mcpPlugin()];

export default defineConfig({
  tanstackStart: {
    // Redirect TanStack Start's bundled server entry to src/server.ts (our SSR error wrapper).
    // nitro/vite builds from this
    server: { entry: "server" },
  },
  vite: {
    plugins: mcpVitePlugins,
  },
});
